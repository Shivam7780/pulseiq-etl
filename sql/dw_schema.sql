CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_department (
    department_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id VARCHAR(20) NOT NULL UNIQUE,
    department_name VARCHAR(150) NOT NULL,
    cost_center VARCHAR(30),
    description TEXT,
    is_leadership BOOLEAN
);

CREATE TABLE IF NOT EXISTS dw.dim_role (
    role_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id VARCHAR(20) NOT NULL UNIQUE,
    department_id VARCHAR(20),
    role_title VARCHAR(150),
    job_level INTEGER,
    grade VARCHAR(50),
    band_min_annual NUMERIC(14,2),
    band_mid_annual NUMERIC(14,2),
    band_max_annual NUMERIC(14,2),
    overtime_eligible BOOLEAN,
    band_reference_year INTEGER
);

CREATE TABLE IF NOT EXISTS dw.dim_employee (
    employee_key BIGINT PRIMARY KEY,
    employee_id VARCHAR(30) NOT NULL,
    full_name VARCHAR(200),
    gender VARCHAR(30),
    date_of_birth DATE,
    hire_date DATE,
    exit_date DATE,
    employment_status VARCHAR(50),
    employment_type VARCHAR(50),
    department_id VARCHAR(20),
    role_id VARCHAR(20),
    role_title VARCHAR(150),
    job_level INTEGER,
    manager_id VARCHAR(30),
    work_location VARCHAR(100),
    work_mode VARCHAR(50),
    highest_education VARCHAR(100),
    valid_from DATE,
    valid_to DATE,
    is_current BOOLEAN,
    change_reason VARCHAR(200)
);

CREATE INDEX IF NOT EXISTS idx_dw_employee_business_id
    ON dw.dim_employee(employee_id);
CREATE INDEX IF NOT EXISTS idx_dw_employee_history
    ON dw.dim_employee(employee_id, valid_from, valid_to);

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year_number INTEGER,
    quarter_number INTEGER,
    month_number INTEGER,
    month_name VARCHAR(20),
    year_month VARCHAR(10),
    week_of_year INTEGER,
    day_of_week VARCHAR(20),
    is_weekend BOOLEAN,
    is_holiday BOOLEAN,
    is_working_day BOOLEAN,
    financial_year VARCHAR(20),
    fiscal_quarter VARCHAR(10),
    fiscal_month_number INTEGER,
    is_month_end BOOLEAN,
    month_start_date DATE,
    month_end_date DATE
);

CREATE TABLE IF NOT EXISTS dw.dim_leave_type (
    leave_type_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_type_code VARCHAR(20) NOT NULL UNIQUE,
    leave_type_name VARCHAR(100),
    pay_type VARCHAR(30),
    annual_quota_days NUMERIC(8,2),
    prorated_for_joiners BOOLEAN,
    carry_forward_allowed BOOLEAN,
    max_carry_forward_days NUMERIC(8,2),
    policy_note TEXT
);

CREATE TABLE IF NOT EXISTS dw.fact_payroll (
    payroll_item_id VARCHAR(30) PRIMARY KEY,
    run_id VARCHAR(30),
    employee_key BIGINT NOT NULL REFERENCES dw.dim_employee(employee_key),
    date_key INTEGER REFERENCES dw.dim_date(date_key),
    period_end_date DATE,
    department_id VARCHAR(20),
    role_id VARCHAR(20),
    payable_days NUMERIC(8,2),
    lop_days NUMERIC(8,2),
    overtime_hours_paid NUMERIC(8,2),
    variable_pay_type VARCHAR(100),
    monthly_fixed_gross NUMERIC(14,2),
    basic_pay NUMERIC(14,2),
    hra NUMERIC(14,2),
    conveyance NUMERIC(14,2),
    medical NUMERIC(14,2),
    special_allowance NUMERIC(14,2),
    earned_fixed_pay NUMERIC(14,2),
    overtime_pay NUMERIC(14,2),
    variable_pay NUMERIC(14,2),
    gross_pay NUMERIC(14,2),
    pf_employee NUMERIC(14,2),
    esi_employee NUMERIC(14,2),
    professional_tax NUMERIC(14,2),
    tds NUMERIC(14,2),
    other_deductions NUMERIC(14,2),
    total_deductions NUMERIC(14,2),
    net_pay NUMERIC(14,2),
    pf_employer NUMERIC(14,2),
    esi_employer NUMERIC(14,2),
    employer_cost NUMERIC(14,2),
    headcount_flag INTEGER
);

CREATE INDEX IF NOT EXISTS idx_dw_payroll_employee_date
    ON dw.fact_payroll(employee_key, date_key);
CREATE INDEX IF NOT EXISTS idx_dw_payroll_run
    ON dw.fact_payroll(run_id);
CREATE INDEX IF NOT EXISTS idx_dw_payroll_period
    ON dw.fact_payroll(period_end_date);

CREATE TABLE IF NOT EXISTS dw.fact_attendance_monthly (
    attendance_fact_id VARCHAR(30) PRIMARY KEY,
    employee_key BIGINT NOT NULL REFERENCES dw.dim_employee(employee_key),
    date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    department_id VARCHAR(20),
    scheduled_days NUMERIC(8,2),
    present_days NUMERIC(8,2),
    wfh_days NUMERIC(8,2),
    half_days_unpaid NUMERIC(8,2),
    paid_leave_days NUMERIC(8,2),
    unpaid_absence_days NUMERIC(8,2),
    late_arrivals INTEGER,
    avg_hours_worked NUMERIC(6,2),
    overtime_hours NUMERIC(8,2),
    attendance_rate NUMERIC(8,4),
    period_end_date DATE
);

CREATE INDEX IF NOT EXISTS idx_dw_attendance_employee_date
    ON dw.fact_attendance_monthly(employee_key, date_key);
CREATE INDEX IF NOT EXISTS idx_dw_attendance_period
    ON dw.fact_attendance_monthly(period_end_date);

CREATE TABLE IF NOT EXISTS dw.fact_leave (
    leave_request_id VARCHAR(30) PRIMARY KEY,
    employee_key BIGINT NOT NULL REFERENCES dw.dim_employee(employee_key),
    leave_type_code VARCHAR(20),
    start_date_key INTEGER REFERENCES dw.dim_date(date_key),
    end_date_key INTEGER REFERENCES dw.dim_date(date_key),
    start_date DATE,
    end_date DATE,
    days NUMERIC(8,2),
    status VARCHAR(30),
    applied_on DATE,
    decided_on DATE,
    approver_id VARCHAR(30),
    reason TEXT
);

CREATE INDEX IF NOT EXISTS idx_dw_leave_employee_start
    ON dw.fact_leave(employee_key, start_date_key);
CREATE INDEX IF NOT EXISTS idx_dw_leave_dates
    ON dw.fact_leave(start_date, end_date);

CREATE TABLE IF NOT EXISTS dw.fact_headcount_monthly (
    date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    month_start_date DATE NOT NULL,
    department_id VARCHAR(20) NOT NULL,
    headcount_start INTEGER,
    hires INTEGER,
    exits INTEGER,
    voluntary_exits INTEGER,
    transfers_in INTEGER,
    transfers_out INTEGER,
    headcount_end INTEGER,
    attrition_rate_monthly_pct NUMERIC(8,2),
    PRIMARY KEY(date_key, department_id)
);

CREATE INDEX IF NOT EXISTS idx_dw_headcount_department_month
    ON dw.fact_headcount_monthly(department_id, month_start_date);
